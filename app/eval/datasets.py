"""Evaluation dataset loading with a fixed, reproducible split.

Synthetic dataset: `data/stress_dataset.csv` (per-item DASS/PSS answers +
Vietnamese free text, generated by `research/generate_dataset.py`) joined with
the frozen stratified split in `data/stress_dataset_split.csv` (created once
by `research/baseline.py`, seed 42). The split is REUSED rather than redrawn
because `models/phobert-stress` was fine-tuned on its train portion - a fresh
split would leak fine-tuning data into the test set.

The unified 4-class label is derived per row with
`app.scoring.derive_ground_truth` (max severity of DASS-21 stress subscale and
PSS-10 category), matching exactly what the application computes at runtime.

Real dataset: `data/real/dataset.csv` in the same schema, produced by
`scripts/export_dataset.py`. Loading is identical from here on.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from app.config import PROJECT_ROOT
from app.scoring import derive_ground_truth

DASS_ITEM_COLS = [f"dass21_q{i}" for i in range(1, 22)]
PSS_ITEM_COLS = [f"pss_q{i}" for i in range(1, 11)]

# Minimum schema every eval dataset must provide.
REQUIRED_COLUMNS = ["student_id", "text", "label", "split"]

STRESS_LEVELS = ["Low", "Moderate", "High", "Severe"]

REAL_DATASET_PATH = PROJECT_ROOT / "data" / "real" / "dataset.csv"


def build_synthetic_dataset() -> pd.DataFrame:
    """Join raw synthetic data with the frozen split; derive the 4-class label."""
    raw = pd.read_csv(PROJECT_ROOT / "data" / "stress_dataset.csv")
    split = pd.read_csv(PROJECT_ROOT / "data" / "stress_dataset_split.csv")

    merged = raw.merge(split[["student_id", "text", "split"]], on="student_id", how="inner")
    merged["label"] = merged.apply(
        lambda row: derive_ground_truth(
            dass_stress_severity=row["dass21_stress_severity"],
            pss_category=row["pss_stress_category"],
        ),
        axis=1,
    )

    keep = (
        ["student_id", "text", "label", "split"]
        + DASS_ITEM_COLS
        + PSS_ITEM_COLS
        + [
            "dass21_depression_severity",
            "dass21_stress_severity",
            "pss_total_score",
            "pss_stress_category",
        ]
    )
    return merged[[c for c in keep if c in merged.columns]].reset_index(drop=True)


def load_eval_dataset(name: str, out_dir: Path | None = None) -> pd.DataFrame:
    """Load the named eval dataset ('synthetic' or 'real') and persist a copy.

    The exact dataframe used for evaluation (including the split column) is
    written to `<out_dir>/dataset_<name>.csv` so every reported number can be
    traced back to a concrete file.
    """
    if name == "synthetic":
        df = build_synthetic_dataset()
    elif name == "real":
        if not REAL_DATASET_PATH.exists():
            raise FileNotFoundError(
                f"Real dataset not found at {REAL_DATASET_PATH}. "
                "Export it first: python scripts/export_dataset.py --split"
            )
        df = pd.read_csv(REAL_DATASET_PATH)
    else:
        raise ValueError(f"unknown dataset {name!r}; expected 'synthetic' or 'real'")

    missing = [c for c in REQUIRED_COLUMNS if c not in df.columns]
    if missing:
        raise ValueError(f"dataset {name!r} is missing required columns: {missing}")
    bad_labels = set(df["label"]) - set(STRESS_LEVELS)
    if bad_labels:
        raise ValueError(f"dataset {name!r} has labels outside {STRESS_LEVELS}: {bad_labels}")

    out = out_dir or (PROJECT_ROOT / "data" / "eval")
    out.mkdir(parents=True, exist_ok=True)
    df.to_csv(out / f"dataset_{name}.csv", index=False)
    return df


def has_questionnaire_items(df: pd.DataFrame) -> bool:
    """True when per-item DASS and PSS answers are available (llm_full needs them)."""
    return all(c in df.columns for c in DASS_ITEM_COLS + PSS_ITEM_COLS)


def dass_answers_from_row(row: pd.Series) -> dict[int, int]:
    return {i: int(row[f"dass21_q{i}"]) for i in range(1, 22)}


def pss_answers_from_row(row: pd.Series) -> dict[int, int]:
    return {i: int(row[f"pss_q{i}"]) for i in range(1, 11)}
